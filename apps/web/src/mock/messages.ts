/** The newest message of a chat, used to seed the list preview. */
export function mockLastMessage(chatId: string): UiMessage {
  const list = mockMessages[chatId] ?? [];
  const last = list[list.length - 1];
  if (last === undefined) {
    throw new Error(`No mock messages for chat ${chatId}`);
  }
  return last;
}
