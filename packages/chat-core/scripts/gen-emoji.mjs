// Generates `src/emoji-table.generated.ts` from unicode-emoji-json. Run
// `pnpm --filter @zilar/chat-core gen:emoji` after bumping the package version.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE = 'unicode-emoji-json';
const PACKAGE_VERSION = '0.9.0';

/** Newer emoji show as empty boxes on older phones, so the table stops at 15.0. */
const MAX_EMOJI_VERSION = 15.0;

const GROUPS = [
  { name: 'Smileys & Emotion', id: 'smileys' },
  { name: 'People & Body', id: 'people' },
  { name: 'Animals & Nature', id: 'animals' },
  { name: 'Food & Drink', id: 'food' },
  { name: 'Travel & Places', id: 'travel' },
  { name: 'Activities', id: 'activities' },
  { name: 'Objects', id: 'objects' },
  { name: 'Symbols', id: 'symbols' },
  { name: 'Flags', id: 'flags' },
];

const require = createRequire(import.meta.url);
const data = require(`${PACKAGE}/data-by-group.json`);

if (!Array.isArray(data)) {
  throw new Error(`${PACKAGE}/data-by-group.json is not an array`);
}

const sourceGroups = new Map(data.map((group) => [group.name, group]));
if (sourceGroups.size !== GROUPS.length) {
  throw new Error(`Expected ${GROUPS.length} emoji groups, got ${sourceGroups.size}`);
}

const categories = GROUPS.map(({ name, id }) => {
  const group = sourceGroups.get(name);
  if (group === undefined) {
    throw new Error(`Missing emoji group: ${name}`);
  }
  const emojis = group.emojis.filter((item) => Number(item.emoji_version) <= MAX_EMOJI_VERSION);
  return { id, emojis };
});

const allEmojis = categories.flatMap(({ emojis }) => emojis);
for (const item of allEmojis) {
  if (item.emoji.includes(' ') || /[\r\n]/.test(item.emoji)) {
    throw new Error(`Emoji ${item.emoji} cannot be packed`);
  }
  if (item.name.includes('|') || /[\r\n]/.test(item.name)) {
    throw new Error(`Emoji name ${item.name} cannot be packed`);
  }
}

// The gate caps a source file at 400 lines and only exempts `.gen.` names, so
// the data is packed into chunks: glyphs space-separated, names `|`-separated.
const GLYPH_CHUNK = 96;
const NAME_CHUNK = 112;

/** Splits packed tokens into lines of at most `maxLength`, at token boundaries. */
function chunk(tokens, separator, maxLength) {
  const chunks = [];
  let current = '';
  for (const token of tokens) {
    const next = current === '' ? token : `${current}${separator}${token}`;
    if (next.length > maxLength && current !== '') {
      chunks.push(current);
      current = token;
    } else {
      current = next;
    }
  }
  if (current !== '') {
    chunks.push(current);
  }
  return chunks;
}

const packedLines = (chunks, indent) =>
  chunks.map((line) => `${' '.repeat(indent)}'${line}',`).join('\n');

const categoryLines = categories
  .map(({ id, emojis }) => {
    const chunks = chunk(
      emojis.map((item) => item.emoji),
      ' ',
      GLYPH_CHUNK,
    );
    return `  ${id}: unpackGlyphs([\n${packedLines(chunks, 4)}\n  ]),`;
  })
  .join('\n');

const nameChunks = chunk(
  categories.flatMap(({ emojis }) => emojis.map((item) => item.name.toLowerCase())),
  '|',
  NAME_CHUNK,
);

const output = `// Generated by scripts/gen-emoji.ts from unicode-emoji-json ${PACKAGE_VERSION} — do not edit.
// Run \`pnpm --filter @zilar/chat-core gen:emoji\` to regenerate.

import type { EmojiCategoryId } from './emoji-table';

/** Joined at token boundaries: no glyph contains a space or a newline. */
const unpackGlyphs = (chunks: readonly string[]): readonly string[] => chunks.join(' ').split(' ');

/** Joined at token boundaries: no name contains a \`|\` or a newline. */
const unpackNames = (chunks: readonly string[]): readonly string[] => chunks.join('|').split('|');

/** Every emoji up to and including Emoji ${MAX_EMOJI_VERSION.toFixed(1)}, grouped by picker category, in Unicode order. */
export const EMOJI_BY_CATEGORY: Record<EmojiCategoryId, readonly string[]> = {
${categoryLines}
};

/** Every generated glyph, in Unicode order: the category order, flattened. */
const GLYPHS_IN_ORDER: readonly string[] = Object.values(EMOJI_BY_CATEGORY).flat();

/** The lowercase Unicode names, in \`GLYPHS_IN_ORDER\` order. */
const NAMES_IN_ORDER: readonly string[] = unpackNames([
${packedLines(nameChunks, 2)}
]);

/** The lowercase Unicode name of every generated glyph. */
export const EMOJI_BASE_NAMES: Readonly<Record<string, string>> = Object.fromEntries(
  GLYPHS_IN_ORDER.map((glyph, index): [string, string] => [glyph, NAMES_IN_ORDER[index] ?? '']),
);
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'emoji-table.generated.ts',
);
writeFileSync(target, output);
console.log(`Wrote ${target} (${allEmojis.length} emoji)`);
